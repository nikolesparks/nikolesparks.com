// Generates dist/_redirects so Netlify issues a 301 from every no-trailing-slash
// URL to its canonical trailing-slash version (e.g. /about -> /about/).
//
// Why: Astro builds directory-format pages (/about/index.html) and sets the
// canonical to /about/, but without an explicit redirect Netlify also serves
// the same content at /about with a 200. Google then indexes both URLs as
// separate pages, splitting ranking signal (confirmed in Search Console). A
// canonical tag is only a hint; a 301 is authoritative.
//
// This scans dist/ for every directory that contains an index.html and writes
// one `/path /path/ 301!` rule per route, so the list stays in sync with the
// site automatically on each build. Runs as an npm `postbuild` step.

import { readdirSync, statSync, existsSync, writeFileSync, appendFileSync } from 'node:fs';
import { join } from 'node:path';

const dist = 'dist';

if (!existsSync(dist)) {
  console.error('[gen-redirects] dist/ not found — run after astro build');
  process.exit(1);
}

/** Collect every route path that resolves to a directory index.html. */
function collectRoutes(dir, base = '') {
  const routes = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (!statSync(full).isDirectory()) continue;
    const route = `${base}/${entry}`;
    if (existsSync(join(full, 'index.html'))) routes.push(route);
    routes.push(...collectRoutes(full, route));
  }
  return routes;
}

const routes = collectRoutes(dist).sort();

// `301!` forces the redirect even though Netlify would otherwise serve the
// no-slash path with a 200. Each rule matches the no-slash path exactly, so the
// already-correct /path/ form never matches and cannot loop.
const rules = routes.map((r) => `${r} ${r}/ 301!`);

const header = `# Auto-generated by scripts/gen-redirects.mjs (npm postbuild). Do not edit by hand.
# Forces canonical trailing-slash URLs so Google indexes one version per page.
`;

const target = join(dist, '_redirects');

// Preserve any hand-authored public/_redirects that Astro copied into dist.
if (existsSync(join('public', '_redirects'))) {
  appendFileSync(target, `\n${header}${rules.join('\n')}\n`);
} else {
  writeFileSync(target, `${header}${rules.join('\n')}\n`);
}

console.log(`[gen-redirects] wrote ${rules.length} trailing-slash redirects to ${target}`);
